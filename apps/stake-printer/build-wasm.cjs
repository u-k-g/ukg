const { execFileSync } = require('node:child_process');
const fs = require('node:fs');
const path = require('node:path');

const root = __dirname;
const env = { ...process.env, PATH: `${process.env.HOME}/.cargo/bin:${process.env.PATH}` };
execFileSync('rustup', [
  'run', 'stable', 'cargo', 'build',
  '--manifest-path', path.join(root, 'printer-core/Cargo.toml'),
  '--target', 'wasm32-unknown-unknown',
  '--release',
], { stdio: 'inherit', env });

const wasm = fs.readFileSync(path.join(
  root,
  'printer-core/target/wasm32-unknown-unknown/release/printer_core.wasm',
));
const boot = `/* generated by build-wasm.cjs */
const bytes = Uint8Array.from(atob(${JSON.stringify(wasm.toString('base64'))}), char => char.charCodeAt(0));
globalThis.PRINTER_EXPORTS = new WebAssembly.Instance(new WebAssembly.Module(bytes)).exports;
`;
fs.writeFileSync(path.join(root, 'printer-boot.js'), boot);
console.log(`Built printer core: ${wasm.length} bytes`);
